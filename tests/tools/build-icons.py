"""Builds the site's own copy of the Phosphor icons, holding only the icons the site uses.

The full Phosphor package is three icon fonts (bold, fill, duotone) of ~450 KB plus three stylesheets
of ~400 KB, all for about a hundred icons. This script keeps those icons and nothing else:

    assets/fonts/phosphor/{bold,fill,duotone}.woff2   the three fonts, cut down
    css/base/phosphor.css                             their @font-face rules and the used icons' rules

Run it again after adding an icon (tests/speed.test.js fails until you do and names the missing one):

    pip install fonttools brotli
    python tests/tools/build-icons.py

Same pinned version as before (2.1.2); the originals are downloaded from jsdelivr each run.
"""
import io
import pathlib
import re
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont

VERSION = '2.1.2'
WEIGHTS = {'bold': 'Bold', 'fill': 'Fill', 'duotone': 'Duotone'}
ROOT = pathlib.Path(__file__).resolve().parents[2]
NOT_ICONS = {'ph-bold', 'ph-fill', 'ph-duotone', 'ph-thin', 'ph-light', 'ph-regular'}


def used_icons():
    names = set()
    files = [ROOT / 'index.html', *ROOT.glob('js/**/*.js'), *ROOT.glob('css/**/*.css')]
    for f in files:
        if f.name == 'phosphor.css':
            continue
        names |= set(re.findall(r'\bph-[a-z0-9]+(?:-[a-z0-9]+)*', f.read_text(encoding='utf-8')))
    return sorted(names - NOT_ICONS)


def fetch(url):
    with urllib.request.urlopen(url) as r:
        return r.read()


def main():
    icons = used_icons()
    out_fonts = ROOT / 'assets' / 'fonts' / 'phosphor'
    out_fonts.mkdir(parents=True, exist_ok=True)
    css_out = [
        '/* Phosphor icons ' + VERSION + ' (MIT, phosphoricons.com), only the ' + str(len(icons)) + ' icons the site uses.',
        '   Generated by tests/tools/build-icons.py: do not edit by hand, run the script after adding an icon. */',
        '',
    ]
    for weight, cap in WEIGHTS.items():
        base = f'https://cdn.jsdelivr.net/npm/@phosphor-icons/web@{VERSION}/src/{weight}/'
        css = fetch(base + 'style.css').decode('utf-8')
        rules = re.findall(r'([^{}]+)\{([^{}]*)\}', css)
        codepoints = set()
        kept = []
        for selector, body in rules:
            sel = selector.strip()
            if sel == '@font-face':
                continue
            if sel == f'.ph-{weight}':
                kept.append((sel, body))
                continue
            m = re.fullmatch(rf'\.ph-{weight}\.(ph-[a-z0-9-]+):(?:before|after)', sel)
            if m and m.group(1) in icons:
                kept.append((sel, body))
                for cp in re.findall(r'content:\s*"\\([0-9a-f]+)"', body):
                    codepoints.add(int(cp, 16))
        font = TTFont(io.BytesIO(fetch(base + f'Phosphor-{cap}.woff2')))
        options = subset.Options()
        options.flavor = 'woff2'
        options.layout_features = []
        options.name_IDs = ['*']
        sub = subset.Subsetter(options)
        sub.populate(unicodes=sorted(codepoints))
        sub.subset(font)
        font.flavor = 'woff2'
        font.save(out_fonts / f'{weight}.woff2')
        css_out.append('@font-face {')
        css_out.append(f'  font-family: "Phosphor-{cap}";')
        css_out.append(f'  src: url("../../assets/fonts/phosphor/{weight}.woff2") format("woff2");')
        css_out.append('  font-weight: normal;\n  font-style: normal;\n  font-display: block;\n}')
        for sel, body in kept:
            lines = [l.strip() for l in body.strip().splitlines() if l.strip() and not l.strip().startswith('/*')]
            css_out.append(sel + ' { ' + ' '.join(lines) + ' }')
        css_out.append('')
        print(weight, len(codepoints), 'glyphs', (out_fonts / f'{weight}.woff2').stat().st_size, 'bytes')
    (ROOT / 'css' / 'base' / 'phosphor.css').write_text('\n'.join(css_out), encoding='utf-8', newline='\n')
    print(len(icons), 'icons')


if __name__ == '__main__':
    main()
